  function slVerdict(sc, p) {
    if (p == null) return 'missing';
    const lo = sc.slBand[0], hi = sc.slBand[1];
    if (p >= lo && p <= hi) return 'ok';
    const wrongSide = sc.side === 'buy' ? p >= sc.entry : p <= sc.entry;
    if (wrongSide) return 'wrongside';
    const inside = sc.side === 'buy' ? p > hi : p < lo;
    return inside ? 'inside' : 'far';
  }

  function wrongText(q, pick, correct) {
    return 'Tum ne <b>' + esc(OPT[q][pick] || '—') + '</b> chuna. ' + esc(NOTE[pick] || '') +
      ' Is chart mein aisa nahi tha. Sahi jawab: <b>' + esc(OPT[q][correct]) + '</b>. ';
  }

  function grade(t) {
    const sc = t.sc, side = sc.side, ans = answersOf(sc), W = TYPES[sc.type].why;
    const parts = {}, rows = [];

    // A, B, C — seedha match
    ['structure', 'liquidity', 'direction'].forEach((q) => {
      const ok = t.picks[q] === ans[q];
      parts[q] = ok ? 25 : 0;
      rows.push({
        q, ok, pick: t.picks[q], correct: ans[q],
        reason: (ok ? '' : wrongText(q, t.picks[q], ans[q])) + esc(tok(W[q], side))
      });
    });

    // D — Execution + Structural SL (dono sahi = 25)
    const exec = t.picks.execution;
    const execOk = exec === ans.execution;
    const trade = isTradeSc(sc);
    const slv = trade ? slVerdict(sc, t.userSL) : 'na';
    const dOk = execOk && (!trade || slv === 'ok');
    const band = trade ? fmt(sc.slBand[0], sc.dp) + ' – ' + fmt(sc.slBand[1], sc.dp) : '';
    let dReason;
    if (dOk) {
      dReason = esc(tok(W.execution, side)) +
        (trade ? ' Tumhara SL <b>' + fmt(t.userSL, sc.dp) + '</b> sahi structural zone (' + band + ') mein tha. ' + esc(tok(W.sl, side)) : '');
    } else if (!execOk) {
      dReason = 'Tum ne <b>' + esc(OPT.execution[exec] || '—') + '</b> chuna. ' + esc(NOTE[exec] || '') +
        ' Sahi: <b>' + esc(OPT.execution[ans.execution]) + '</b>. ' + esc(tok(W.execution, side)) +
        (trade ? ' Sahi Structural SL zone: <b>' + band + '</b>. ' + esc(tok(W.sl, side)) : '');
    } else {
      const p = t.userSL == null ? '—' : fmt(t.userSL, sc.dp);
      const why = {
        missing: 'Stop-Loss lagaya hi nahi gaya.',
        wrongside: 'SL ' + p + ' entry ke ghalat taraf tha — ' + tok('{Buy} mein SL hamesha entry ke {neeche} hota hai.', side),
        inside: 'Execution sahi tha, lekin SL ' + p + ' structure ke andar (bohat qareeb) tha — normal retest hi tumhe bahar nikal deta.',
        far: 'Execution sahi tha, lekin SL ' + p + ' bohat door tha — zaroorat se zyada risk aur R:R kharab.'
      }[slv];
      dReason = esc(why) + ' Sahi Structural SL zone: <b>' + band + '</b>. ' + esc(tok(W.sl, side));
    }
    parts.stoploss = dOk ? 25 : 0;
    rows.push({ q: 'execution', ok: dOk, pick: exec, correct: ans.execution, reason: dReason, slv });

    const score = parts.structure + parts.liquidity + parts.direction + parts.stoploss;
    return { score, parts, rows, slOk: slv === 'ok' };
  }

